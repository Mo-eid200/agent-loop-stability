#!/usr/bin/env python3
"""Run every verification layer and write RESULTS.md (about 5 minutes).

  1. tests.py          exact theory, Monte Carlo, synthetic recovery, CLI
  2. validate_real.py  54 real LLM-agent runs + 4,050 real latency measurements
  3. mutate.py         11 planted bugs, each must be caught by the tests

Exit code 0 only if every layer passes.
"""
from __future__ import annotations

import subprocess
import sys
import tempfile
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent


def main() -> int:
    parts = ["# Results", "", f"Generated by `run_all.py` on {time.strftime('%Y-%m-%d %H:%M')}.", ""]
    ok_all = True
    with tempfile.TemporaryDirectory() as td:
        steps = [("1. Verification suite", ["tests.py"], None),
                 ("2. Validation on real data", ["validate_real.py", f"{td}/VALIDATION.md"],
                  f"{td}/VALIDATION.md"),
                 ("3. Mutation testing", ["mutate.py", f"{td}/MUTATION.md"], f"{td}/MUTATION.md")]
        for title, cmd, report in steps:
            print(f"== {title}", flush=True)
            t0 = time.time()
            r = subprocess.run([sys.executable, *cmd], cwd=HERE, capture_output=True, text=True)
            ok = r.returncode == 0
            ok_all &= ok
            print(f"   {'PASS' if ok else 'FAIL'} ({time.time() - t0:.0f}s)", flush=True)
            if report and Path(report).exists():
                body = Path(report).read_text().split("\n", 1)[1].strip()
            else:
                body = "```\n" + r.stdout.strip() + "\n```"
            parts += [f"## {title}: {'PASS' if ok else 'FAIL'}", "", body, ""]
    parts.append(f"**Every layer passes: {ok_all}**")
    (HERE / "RESULTS.md").write_text("\n".join(parts) + "\n")
    print(f"\nevery layer passes: {ok_all}  ->  RESULTS.md")
    return 0 if ok_all else 1


if __name__ == "__main__":
    sys.exit(main())
